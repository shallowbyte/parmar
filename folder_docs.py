#!/usr/bin/env python3
"""Regenerate the per-directory README.md files.

GitHub renders a README.md inside any directory listing, so each data directory
explains itself when someone browses to it. These are generated rather than
hand-written so the counts, sizes and checksums cannot drift away from the files
they describe -- re-run this after any sweep or analysis.

    python folder_docs.py
"""

import hashlib
import json
import os
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.abspath(__file__))
TIER_ORDER = ["64MB", "256MB", "1GB", "4GB", "8GB"]
STAMP = ("<!-- generated by folder_docs.py -- edit that script, not this file -->")


def human(n):
    for unit in ("B", "KB", "MB", "GB"):
        if abs(n) < 1024 or unit == "GB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024


def size(path):
    return os.path.getsize(path) if os.path.exists(path) else 0


def write(rel, body):
    path = os.path.join(ROOT, rel, "README.md")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body.rstrip() + "\n\n" + STAMP + "\n")
    print(f"  wrote {rel}/README.md")


def load_results():
    d = os.path.join(ROOT, "results")
    per_file, rows = {}, {}
    if not os.path.isdir(d):
        return per_file, rows
    for fn in sorted(os.listdir(d)):
        if not fn.endswith(".jsonl"):
            continue
        rs = []
        with open(os.path.join(d, fn), encoding="utf-8") as fh:
            for line in fh:
                line = line.strip()
                if line:
                    r = json.loads(line)
                    rs.append(r)
                    rows[(r["row_id"], r["corpus_tier"])] = r
        per_file[fn] = rs
    return per_file, rows


